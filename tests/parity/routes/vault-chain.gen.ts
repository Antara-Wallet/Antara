/**
 * Generates tests/parity/routes/vault-chain.ts: the parity fixture vault's addresses and its
 * Squads account bytes, built with the real Squads serializers (src/solares/paired/testFixtures.ts)
 * from the fixed keys in tests/parity/keys.ts. The Playwright runner cannot load @sqds/multisig
 * or @solana/web3.js ("module is not linked"), so the bytes are generated here once and checked.
 *
 *   npx tsx tests/parity/routes/vault-chain.gen.ts           write vault-chain.ts
 *   npx tsx tests/parity/routes/vault-chain.gen.ts --check   exit 1 when vault-chain.ts is stale, or when any
 *                                                            vault route answer fails the wallet's own parsers
 * Never imported by the runner. Seeds are public; these keys hold nothing and sign nothing.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as multisig from '@sqds/multisig';
import { PublicKey } from '@solana/web3.js';
import { PAIRED_POLICY_VERSION, SOLANA_USDC_MINT, SPL_TOKEN_PROGRAM_ID, SQUADS_PROGRAM_ID, decodePairedMultisig, pairedVaultAddresses } from '../../../src/solares/paired/solanaDecode';
import { multisigAccount, tokenAccount, usdcAta } from '../../../src/solares/paired/testFixtures';
import { parsePairedAccount, parsePairedApproval, parsePairedConfig, parsePairedUsage } from '../../../src/solares/vaults/pairedApi';
import { parseLayerResults, parseReleaseChallenge, parseVaultLayers } from '../../../src/solares/layers/schema';
import { PARITY_KEYS } from '../keys';

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, 'vault-chain.ts');

function build() {
  const createKey = new PublicKey(PARITY_KEYS.createKey);
  const multisigPda = multisig.getMultisigPda({ createKey })[0];
  const keys = {
    user: PARITY_KEYS.user, guardian: PARITY_KEYS.guardian, createKey: PARITY_KEYS.createKey,
    multisig: multisigPda.toBase58(), vault: multisig.getVaultPda({ multisigPda, index: 0 })[0].toBase58(),
  };
  if (pairedVaultAddresses(keys.multisig).vault !== keys.vault) throw new Error('Vault PDA mismatch.');
  const account = multisigAccount(keys);
  // The same decoder verifyPairedSolanaVault uses must accept it.
  decodePairedMultisig(account, { guardian: keys.guardian, user: keys.user, spendingLimitCount: 0 });
  const vaultUsdc = usdcAta(keys.vault, SOLANA_USDC_MINT, true);
  const token = tokenAccount({ address: vaultUsdc, owner: keys.vault });
  const lines = [
    '// GENERATED by tests/parity/routes/vault-chain.gen.ts from tests/parity/keys.ts. Do not edit by hand;',
    '// regenerate with `npx tsx tests/parity/routes/vault-chain.gen.ts` and check with `--check`.',
    '// Squads v4 account bytes of the parity fixture vault (members user:7, guardian:2, threshold 2, no time lock).',
    '',
    'export const PARITY_VAULT = Object.freeze({',
    `  user: '${keys.user}',`,
    `  guardian: '${keys.guardian}',`,
    `  createKey: '${keys.createKey}',`,
    `  multisig: '${keys.multisig}',`,
    `  /** Squads vault PDA (index 0): the deposit address. */`,
    `  depositAddress: '${keys.vault}',`,
    `  /** The vault's Circle USDC associated token account. */`,
    `  usdcAccount: '${vaultUsdc}',`,
    '});',
    `export const SQUADS_PROGRAM_ID = '${SQUADS_PROGRAM_ID}';`,
    `export const SPL_TOKEN_PROGRAM_ID = '${SPL_TOKEN_PROGRAM_ID}';`,
    `export const PAIRED_POLICY_VERSION = '${PAIRED_POLICY_VERSION}';`,
    `export const MULTISIG_ACCOUNT_BASE64 = '${Buffer.from(account.data).toString('base64')}';`,
    `export const USDC_TOKEN_ACCOUNT_BASE64 = '${Buffer.from(token.data).toString('base64')}';`,
    '',
  ];
  return lines.join('\n');
}

const output = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== output) { console.error('tests/parity/routes/vault-chain.ts is stale. Run: npx tsx tests/parity/routes/vault-chain.gen.ts'); process.exit(1); }
  // Every vault route answer must pass the wallet's own strict parsers, so a capture never shows a parse error by accident.
  const routes = await import('./vault');
  const { PARITY_VAULT } = await import('./vault-chain');
  parsePairedConfig(routes.configBody(), PARITY_VAULT.guardian, 'mainnet-beta');
  for (const profile of routes.VAULT_PROFILES) {
    parsePairedAccount(routes.accountBody(profile));
    const layers = routes.layersAnswer(profile);
    if (layers.status === 200) parseVaultLayers(layers.body, PARITY_VAULT.multisig);
  }
  parsePairedUsage(routes.usageBody(), PARITY_VAULT.multisig);
  parseReleaseChallenge(routes.challengeBody(), PARITY_VAULT.multisig, routes.RELEASE_INDEX);
  parsePairedApproval(routes.approvalBody());
  parseLayerResults(routes.layerFailedBody().layers);
  console.log('vault-chain.ts is current; every vault route answer parses.');
} else {
  fs.writeFileSync(target, output);
  console.log(`Wrote ${path.relative(process.cwd(), target)}`);
}
